/**
 * What the editor's AI needs to KNOW about the cloned site before it touches anything, measured on the real canvas:
 *
 *  - buildSiteProfile(): the site's visual identity (colors with their roles, fonts, button and card style, spacing). It goes in the
 *    first message of every task, and identityIssues() checks what the AI created against it, so "make it look like the site" is
 *    enforced by the tools, not left to the model's good will.
 *  - detectWidgets(): things that were interactive on the original (carousels, sliders of testimonials) and lost their scripts in the
 *    clone. The model is told where they are instead of having to guess.
 *  - makeCarousel() / checkMotion(): a carousel that works with no script at all (CSS only: autoplay, pause on hover, clickable dots),
 *    generated by code, and the measurement that proves it moves. The model never hand-writes keyframes for this.
 */
import { clip, contentRoot, describePage, findSections, hex, isElement, kindOfEl, parseColor, realChildren, relLum, stableId, txt, type EngineCtx } from './ai-engine'

type Comp = any
type RGB = [number, number, number]

/* ───────── small helpers ───────── */

const rgbOfHex = (h: string | undefined): RGB | null => { const m = h ? /^#([0-9a-f]{6})$/i.exec(h) : null; return m ? ([0, 2, 4].map(i => parseInt(m[1].slice(i, i + 2), 16)) as RGB) : null }
const toHex = (c: RGB) => '#' + c.map(n => Math.round(n).toString(16).padStart(2, '0')).join('')
const dist = (a: RGB, b: RGB) => Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2])
const sat = (c: RGB) => Math.max(...c) - Math.min(...c)
const solid = (s: string | undefined): RGB | null => { const c = s ? parseColor(s) : null; return c && c[3] > 0.5 ? [c[0], c[1], c[2]] : null }
const px = (s: string | undefined) => { const n = parseFloat(s || ''); return Number.isFinite(n) ? n : 0 }
const firstFont = (s: string) => (s || '').split(',')[0].replace(/["']/g, '').trim()

function mode<T extends string | number>(list: T[]): T | undefined {
  const n = new Map<T, number>()
  for (const v of list) n.set(v, (n.get(v) || 0) + 1)
  let best: T | undefined, c = 0
  for (const [v, k] of n) if (k > c) { best = v; c = k }
  return best
}

/** a flat color, or the first color of a gradient background */
function paintOf(cs: CSSStyleDeclaration): RGB | null {
  const flat = solid(cs.backgroundColor)
  if (flat) return flat
  const g = /gradient/i.test(cs.backgroundImage) ? cs.backgroundImage.match(/rgba?\([^)]+\)/) : null
  return g ? solid(g[0]) : null
}

const contrastBetween = (a: RGB, b: RGB) => { const x = relLum(a), y = relLum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05) }
const winOf = (ctx: EngineCtx) => ctx.editor.Canvas.getDocument()?.defaultView as Window | undefined

/* ═════════════════════════ the site's identity ═════════════════════════ */

/**
 * The color the page really sits on. What a visitor sees is what the sections paint: when opaque section backgrounds cover most of
 * the page's height, the one covering the most is the page's background (the white <body> of the editor only shows in the margins).
 * Otherwise the first opaque background going up from the content (clones often put it on a wrapper), then white.
 */
function pageBackground(ctx: EngineCtx, win: Window, rootEl: HTMLElement): string {
  const sec = sectionBackground(ctx, win)
  if (sec.coverage >= 0.6) return sec.color
  const ink = solid(win.getComputedStyle(rootEl).color)
  for (let n: HTMLElement | null = rootEl; n; n = n.parentElement) {
    const c = solid(win.getComputedStyle(n).backgroundColor)
    // a background the page's own text cannot be read on (white text on white after an edit that went wrong) is not the site's look
    if (c && (!ink || contrastBetween(c, ink) >= 2.2)) return toHex(c)
    if (c) break
  }
  return sec.color
}

/**
 * What a section really paints: its own background, or (blocks wrapped in a transparent <section> of the editor's own) the one of the
 * child that fills the wrapper.
 */
function paintedBg(el: HTMLElement, win: Window): RGB | null {
  let cur: HTMLElement | null = el
  for (let d = 0; cur && d < 3; d++) {
    const c = solid(win.getComputedStyle(cur).backgroundColor)
    if (c) return c
    const box: DOMRect = cur.getBoundingClientRect()
    const kids: HTMLElement[] = (Array.from(cur.children) as HTMLElement[]).filter(k => k.getBoundingClientRect().height > 0)
    const fill: HTMLElement | undefined = kids.length === 1 ? kids[0] : kids.find(k => k.getBoundingClientRect().height >= box.height * 0.9)
    cur = fill && fill.getBoundingClientRect().width >= box.width * 0.9 ? fill : null
  }
  return null
}

/** The background that covers the most height among the page's sections, and how much of the page's height opaque backgrounds cover. */
function sectionBackground(ctx: EngineCtx, win: Window): { color: string; coverage: number } {
  const byHeight = new Map<string, number>()
  let total = 0, covered = 0
  for (const comp of findSections(contentRoot(ctx)).list) {
    const el = comp.getEl?.() as HTMLElement | undefined
    if (!isElement(el)) continue
    const h = el.getBoundingClientRect().height
    total += h
    const c = paintedBg(el, win)
    if (c) { byHeight.set(toHex(c), (byHeight.get(toHex(c)) || 0) + h); covered += h }
  }
  let best = '#ffffff', h = 0
  for (const [c, v] of byHeight) if (v > h) { best = c; h = v }
  return { color: best, coverage: total > 0 ? covered / total : 0 }
}

export interface SiteProfile {
  mood: 'dark' | 'light'
  pageBg: string
  text: string
  muted?: string
  accent?: string
  accent2?: string
  onAccent?: string
  surfaces: string[]
  headingFont: string
  bodyFont: string
  headingWeight?: string
  headingTracking?: string
  headingCase?: string
  button?: { bg: string; color: string; radius: string; weight: string; padding: string; case?: string; tracking?: string; border?: string }
  cardRadius?: string
  cardShadow?: string
  sectionPadY?: number
  contentWidth?: number
  palette: string[]
  /** set when the page as it is now looks broken (unreadable): what the model must know about it */
  note?: string
}

export function buildSiteProfile(ctx: EngineCtx): SiteProfile {
  const win = winOf(ctx)
  const rootEl = contentRoot(ctx).getEl?.() as HTMLElement | undefined
  const { outline } = describePage(ctx, null, { stable: true })
  const pageBg = win && isElement(rootEl) ? pageBackground(ctx, win, rootEl) : (outline.page.bg && /^#/.test(outline.page.bg) ? outline.page.bg : '#ffffff')
  const pageRgb = rgbOfHex(pageBg) || [255, 255, 255]
  const out: SiteProfile = {
    mood: relLum(pageRgb) < 0.35 ? 'dark' : 'light', pageBg, text: outline.page.color || '#000000',
    surfaces: [], headingFont: outline.page.font || 'sans-serif', bodyFont: outline.page.font || 'sans-serif', palette: [],
  }
  if (!win || !isElement(rootEl)) return out

  const heads: { font: string; weight: string; track: string; tcase: string; color: string }[] = []
  const bodies: { font: string; color: string }[] = []
  const btns: { bg: RGB; color: string; radius: string; weight: string; padding: string; tcase: string; track: string; border: string }[] = []
  const links: RGB[] = []
  const cardBg: string[] = [], cardRadius: string[] = [], cardShadow: string[] = []
  const widths: number[] = []

  for (const el of (Array.from(rootEl.querySelectorAll('*')) as HTMLElement[]).slice(0, 2600)) {
    const cs = win.getComputedStyle(el)
    if (cs.display === 'none' || cs.visibility === 'hidden') continue
    const r = el.getBoundingClientRect()
    if (r.width <= 0 || r.height <= 0) continue
    const kind = kindOfEl(el, cs)
    if (kind === 'heading') heads.push({ font: firstFont(cs.fontFamily), weight: cs.fontWeight, track: cs.letterSpacing, tcase: cs.textTransform, color: hex(cs.color) || '' })
    else if (kind === 'text') bodies.push({ font: firstFont(cs.fontFamily), color: hex(cs.color) || '' })
    else if (kind === 'button') {
      const bg = paintOf(cs)
      if (bg) btns.push({ bg, color: hex(cs.color) || '', radius: cs.borderTopLeftRadius, weight: cs.fontWeight, padding: `${cs.paddingTop} ${cs.paddingLeft}`, tcase: cs.textTransform, track: cs.letterSpacing, border: px(cs.borderTopWidth) > 0 ? `${cs.borderTopWidth} ${hex(cs.borderTopColor) || ''}` : '' })
    } else if (kind === 'link') { const c = solid(cs.color); if (c) links.push(c) }
    // cards: a rounded box of its own, sized like a card, holding content, that stands out from what is behind it
    const rad = px(cs.borderTopLeftRadius)
    if (rad >= 6 && r.width >= 160 && r.width <= 900 && r.height >= 70 && (el.children.length > 0)) {
      const bg = solid(cs.backgroundColor)
      const hasEdge = px(cs.borderTopWidth) > 0 || (cs.boxShadow && cs.boxShadow !== 'none')
      if (bg || hasEdge) {
        if (bg) cardBg.push(toHex(bg))
        cardRadius.push(cs.borderTopLeftRadius)
        if (cs.boxShadow && cs.boxShadow !== 'none') cardShadow.push(cs.boxShadow)
      }
    }
  }

  out.headingFont = mode(heads.map(h => h.font).filter(Boolean)) || out.headingFont
  out.bodyFont = mode(bodies.map(b => b.font).filter(Boolean)) || out.bodyFont
  const hc = mode(heads.map(h => h.color).filter(Boolean)); if (hc) out.text = hc
  {
    const bg = rgbOfHex(out.pageBg), tx = rgbOfHex(out.text)
    if (bg && tx && contrastBetween(bg, tx) < 2.2) {
      // e.g. white headings on a white page: an edit went wrong. The real look is what the sections themselves paint.
      const alt = sectionBackground(ctx, win).color
      const altRgb = rgbOfHex(alt)
      let fixed: string | null = altRgb && contrastBetween(altRgb, tx) >= 2.2 ? alt : null
      // nothing paints a readable background any more: the most used color of the site's own palette that the headings read well on
      if (!fixed) fixed = outline.palette.find(h => { const c = rgbOfHex(h); return !!c && contrastBetween(c, tx) >= 4 }) || null
      if (fixed) {
        out.note = `ATENÇÃO: nesta página os títulos (${out.text}) estão quase da mesma cor do fundo atual (${out.pageBg}), então ela está ilegível: foi uma edição anterior que deu errado. O visual ORIGINAL do site é o descrito abaixo (fundo ${fixed}); ao mexer na página, devolva esse fundo em vez de manter o estado quebrado.`
        out.pageBg = fixed
        out.mood = relLum(rgbOfHex(fixed)!) < 0.35 ? 'dark' : 'light'
      }
    }
  }
  const bodyColors = bodies.map(b => b.color).filter(Boolean)
  const bc = mode(bodyColors)
  if (bc && !hc) out.text = bc
  const muted = mode(bodyColors.filter(c => c !== out.text))
  if (muted) out.muted = muted
  out.headingWeight = mode(heads.map(h => h.weight))
  const track = mode(heads.map(h => h.track).filter(t => t && t !== 'normal'))
  if (track) out.headingTracking = track
  const hcase = mode(heads.map(h => h.tcase))
  if (hcase && hcase !== 'none') out.headingCase = hcase

  // accent: the most used saturated color of the buttons, else of the links, else the most saturated color of the page
  const pool = (btns.map(b => b.bg).filter(c => sat(c) >= 40).map(toHex)).concat(links.filter(c => sat(c) >= 60).map(toHex))
  const accent = mode(pool) || (outline.palette.map(rgbOfHex).filter((c): c is RGB => !!c && sat(c) >= 60).map(toHex)[0])
  if (accent) {
    out.accent = accent
    const second = mode(pool.filter(c => { const a = rgbOfHex(c), b = rgbOfHex(accent); return !!a && !!b && dist(a, b) > 90 }))
    if (second) out.accent2 = second
  }
  const primary = btns.filter(b => !accent || toHex(b.bg) === accent)
  const main = primary.length ? primary : btns
  if (main.length) {
    const b = main[0]
    const bgHex = mode(main.map(x => toHex(x.bg))) || toHex(b.bg)
    out.button = { bg: bgHex, color: mode(main.map(x => x.color)) || b.color, radius: mode(main.map(x => x.radius)) || b.radius, weight: mode(main.map(x => x.weight)) || b.weight, padding: mode(main.map(x => x.padding)) || b.padding, case: mode(main.map(x => x.tcase).filter(c => c !== 'none')), tracking: mode(main.map(x => x.track).filter(t => t && t !== 'normal')), border: mode(main.map(x => x.border).filter(Boolean)) }
    out.onAccent = out.button.color
  }
  out.cardRadius = mode(cardRadius)
  out.cardShadow = mode(cardShadow)

  // sections: backgrounds that differ from the page, vertical padding, width of the content column
  const secBg: string[] = [], pads: number[] = []
  for (const comp of findSections(contentRoot(ctx)).list) {
    const el = comp.getEl?.() as HTMLElement | undefined
    if (!isElement(el)) continue
    const cs = win.getComputedStyle(el)
    const bg = paintedBg(el, win)
    if (bg) secBg.push(toHex(bg))
    let pt = px(cs.paddingTop)
    if (!pt && el.firstElementChild) pt = px(win.getComputedStyle(el.firstElementChild).paddingTop)
    if (pt >= 24) pads.push(Math.round(pt / 8) * 8)
    const inner = [el, ...Array.from(el.querySelectorAll(':scope > *, :scope > * > *')) as HTMLElement[]].slice(0, 12).find(e => { const mw = px(win.getComputedStyle(e).maxWidth); return mw >= 600 && mw < 2000 })
    if (inner) widths.push(Math.round(px(win.getComputedStyle(inner).maxWidth) / 20) * 20)
  }
  out.sectionPadY = mode(pads)
  out.contentWidth = mode(widths)
  const distinct = (list: string[]) => { const seen: string[] = []; for (const c of list) if (c !== pageBg && !seen.includes(c)) seen.push(c); return seen }
  const count = (list: string[]) => { const n = new Map<string, number>(); list.forEach(c => n.set(c, (n.get(c) || 0) + 1)); return [...n.entries()].sort((a, b) => b[1] - a[1]).map(([c]) => c) }
  out.surfaces = distinct(count(secBg.concat(cardBg))).slice(0, 4)

  // every color the site really uses (what new content may use without looking foreign)
  const palette: string[] = []
  for (const c of [pageBg, out.text, out.muted, out.accent, out.accent2, out.onAccent, out.button?.bg, ...out.surfaces, ...outline.palette]) {
    const h = typeof c === 'string' ? (/^#[0-9a-f]{6}$/i.test(c) ? c : hex(c)) : undefined
    const rgb = rgbOfHex(h)
    if (rgb && !palette.some(p => dist(rgbOfHex(p)!, rgb) < 28)) palette.push(h!)
  }
  out.palette = palette.slice(0, 12)
  return out
}

/** The compact, Portuguese description the model reads (about 800 characters). */
export function profileText(p: SiteProfile): string {
  const L: string[] = []
  if (p.note) L.push(p.note)
  L.push(`- Tema ${p.mood === 'dark' ? 'ESCURO' : 'CLARO'}: fundo da página ${p.pageBg}, texto ${p.text}${p.muted ? `, texto apagado ${p.muted}` : ''}.`)
  if (p.accent) L.push(`- Cor de destaque (botões, links, ícones, realces): ${p.accent}${p.accent2 ? `; segunda cor: ${p.accent2}` : ''}${p.onAccent ? `; texto sobre o destaque: ${p.onAccent}` : ''}.`)
  if (p.surfaces.length) L.push(`- Superfícies (seções e cartões): ${p.surfaces.join(', ')}.`)
  L.push(`- Fontes: títulos "${p.headingFont}"${p.headingWeight ? ` peso ${p.headingWeight}` : ''}${p.headingTracking ? `, espaçamento ${p.headingTracking}` : ''}${p.headingCase ? `, ${p.headingCase}` : ''}; texto "${p.bodyFont}".`)
  if (p.button) L.push(`- Botão principal: fundo ${p.button.bg}, texto ${p.button.color}, raio ${p.button.radius}, peso ${p.button.weight}, padding ${p.button.padding}${p.button.case ? `, ${p.button.case}` : ''}${p.button.border ? `, borda ${p.button.border}` : ''}.`)
  if (p.cardRadius) L.push(`- Cartões: raio ${p.cardRadius}${p.cardShadow ? `, sombra ${clip(p.cardShadow, 70)}` : ', sem sombra'}.`)
  if (p.sectionPadY || p.contentWidth) L.push(`- Ritmo: seções com padding vertical de ~${p.sectionPadY ?? '?'}px${p.contentWidth ? `, conteúdo com largura máxima de ~${p.contentWidth}px` : ''}.`)
  L.push(`- Paleta completa do site: ${p.palette.join(', ')}.`)
  return L.join('\n')
}

/* ───────── is what the AI made still "this site"? ───────── */

export function identityIssues(ctx: EngineCtx, p: SiteProfile, comps: Comp[]): string[] {
  const win = winOf(ctx)
  if (!win || !p.palette.length) return []
  const pal = p.palette.map(rgbOfHex).filter((c): c is RGB => !!c)
  const fonts = new Set([p.headingFont, p.bodyFont].map(f => f.toLowerCase()))
  const generic = /^(serif|sans-serif|monospace|system-ui|inherit|initial|ui-|-apple-system|emoji)/i
  const neutral = (c: RGB) => Math.min(...c) >= 245 || Math.max(...c) <= 10
  const near = (c: RGB) => pal.reduce((best, q) => (dist(c, q) < dist(c, best) ? q : best), pal[0])
  const seen = new Set<string>()
  const msgs: string[] = []
  const flag = (el: HTMLElement, what: string, c: RGB) => {
    const key = what + toHex(c)
    if (seen.has(key) || msgs.length >= 5) return
    seen.add(key)
    msgs.push(`${what} ${toHex(c)} em <${el.tagName.toLowerCase()}>${clip(txt(el), 24) ? ` "${clip(txt(el), 24)}"` : ''} não existe na identidade do site; a mais parecida é ${toHex(near(c))} (use as cores da paleta)`)
  }
  let fontFlagged = false
  for (const comp of comps) {
    const root = comp?.getEl?.()
    if (!isElement(root)) continue
    for (const el of [root, ...(Array.from(root.querySelectorAll('*')) as HTMLElement[])].slice(0, 250)) {
      const cs = win.getComputedStyle(el)
      if (cs.display === 'none' || cs.visibility === 'hidden') continue
      const r = el.getBoundingClientRect()
      if (r.width <= 0 || r.height <= 0) continue
      const color = solid(cs.color)
      if (color && !neutral(color) && txt(el) && el.children.length === 0 && Math.min(...pal.map(q => dist(color, q))) > 70) flag(el, 'cor de texto', color)
      const bg = solid(cs.backgroundColor)
      if (bg && !neutral(bg) && Math.min(...pal.map(q => dist(bg, q))) > 70) flag(el, 'cor de fundo', bg)
      const bdr = px(cs.borderTopWidth) > 0 ? solid(cs.borderTopColor) : null
      if (bdr && !neutral(bdr) && Math.min(...pal.map(q => dist(bdr, q))) > 70) flag(el, 'cor de borda', bdr)
      const f = firstFont(cs.fontFamily).toLowerCase()
      if (!fontFlagged && txt(el) && el.children.length === 0 && f && !fonts.has(f) && !generic.test(f)) {
        fontFlagged = true
        msgs.push(`fonte "${firstFont(cs.fontFamily)}" não é do site: use "${p.headingFont}" nos títulos e "${p.bodyFont}" no texto (ou deixe herdar)`)
      }
    }
  }
  return msgs
}

/** Colors written in a style change or in CSS text (set_styles / add_css) that the site does not use. */
export function cssDrift(p: SiteProfile, text: string): string | null {
  const pal = p.palette.map(rgbOfHex).filter((c): c is RGB => !!c)
  if (!pal.length) return null
  const bad: string[] = []
  const check = (c: RGB | null, raw: string) => {
    if (!c || Math.min(...c) >= 245 || Math.max(...c) <= 10) return
    const best = pal.reduce((b, q) => (dist(c, q) < dist(c, b) ? q : b), pal[0])
    if (dist(c, best) > 70 && !bad.some(x => x.startsWith(raw))) bad.push(`${raw} (a mais parecida do site é ${toHex(best)})`)
  }
  for (const m of text.matchAll(/#([0-9a-f]{6}|[0-9a-f]{3})\b/gi)) {
    const h = m[1].length === 3 ? m[1].split('').map(x => x + x).join('') : m[1]
    check(rgbOfHex('#' + h.toLowerCase()), '#' + m[1].toLowerCase())
  }
  for (const m of text.matchAll(/rgba?\(\s*(\d+)[,\s]+(\d+)[,\s]+(\d+)(?:[,\s/]+([\d.]+))?\s*\)/gi)) {
    if (m[4] !== undefined && parseFloat(m[4]) < 0.5) continue
    check([+m[1], +m[2], +m[3]], `rgb(${m[1]},${m[2]},${m[3]})`)
  }
  return bad.length ? `Cores fora da identidade do site: ${bad.slice(0, 4).join('; ')}. Use as cores do site, a menos que o pedido do usuário tenha pedido exatamente essa cor.` : null
}

/** apply_theme with a color the site does not use: say so, so the model asks itself if the request really wanted that. */
export function themeDrift(p: SiteProfile, theme: { accent?: string; background?: string }): string | null {
  const parts: string[] = []
  const far = (a?: string, b?: string) => { const x = rgbOfHex(a), y = rgbOfHex(b); return !!x && !!y && dist(x, y) > 70 }
  if (theme.accent && p.accent && far(theme.accent, p.accent)) parts.push(`destaque ${theme.accent} (o do site é ${p.accent})`)
  if (theme.background && far(theme.background, p.pageBg)) parts.push(`fundo ${theme.background} (o do site é ${p.pageBg})`)
  return parts.length ? `Este tema muda a identidade do site: ${parts.join('; ')}. Só mantenha se o pedido do usuário pediu essa mudança de cores.` : null
}

/* ═════════════════════════ widgets that lost their script ═════════════════════════ */

export interface Widget {
  id: string
  kind: 'carousel'
  shape: 'empilhado' | 'trilho' | 'nomeado' | 'com_bolinhas' | 'montado'
  slides: number
  slideIds: string[]
  where: string
  evidence: string
  state: string
}

const NAMED = /(carousel|carrossel|slider|swiper|slick|owl-|splide|glide|flickity|testimonial|depoimento|tslide|slides?\b)/i
const isControl = (c: Comp) => { const cls = String(c.getEl?.()?.className || ''); return /\bvaic-(in|nav)\b/.test(cls) }

function visibleNow(el: HTMLElement, win: Window): boolean {
  const cs = win.getComputedStyle(el)
  const r = el.getBoundingClientRect()
  return cs.display !== 'none' && cs.visibility !== 'hidden' && parseFloat(cs.opacity) > 0.5 && r.width > 0 && r.height > 0
}

export function detectWidgets(ctx: EngineCtx): Widget[] {
  const win = winOf(ctx)
  if (!win) return []
  const found: Widget[] = []
  let budget = 3000

  const scan = (comp: Comp, depth: number) => {
    if (budget-- <= 0 || depth > 16 || found.length >= 8) return
    const el = comp.getEl?.()
    if (!isElement(el)) return
    const kids = realChildren(comp).filter(k => !isControl(k) && !/^(script|style|link|input|label)$/i.test(String(k.getEl?.()?.tagName)))
    if (kids.length >= 2) {
      const tagOf = (k: Comp) => String(k.getEl().tagName)
      const tag = mode(kids.map(tagOf))
      const slides = kids.filter(k => tagOf(k) === tag && (txt(k.getEl()).length >= 8 || k.getEl().querySelector('img,video')))
      if (slides.length >= 2 && slides.length >= Math.ceil(kids.length * 0.7)) {
        const els = slides.map(s => s.getEl() as HTMLElement)
        const cssOf = els.map(e => win.getComputedStyle(e))
        const rects = els.map(e => e.getBoundingClientRect())
        const sameBox = (a: DOMRect, b: DOMRect) => a.width > 0 && b.width > 0 && Math.abs(a.left - b.left) < 6 && Math.abs(a.top - b.top) < 6 && Math.abs(a.width - b.width) < 6 && Math.abs(a.height - b.height) < 6
        const stackedPairs = rects.filter((r, i) => rects.some((o, j) => j !== i && sameBox(r, o))).length
        const hidden = els.filter((e, i) => cssOf[i].display === 'none' || cssOf[i].visibility === 'hidden' || parseFloat(cssOf[i].opacity) < 0.05).length
        const firstClass = (e: HTMLElement) => (String(e.className || '').split(/\s+/)[0] || '')
        const sameClass = firstClass(els[0]) !== '' && els.every(e => firstClass(e) === firstClass(els[0]))
        const cs = win.getComputedStyle(el)
        const scrollsX = /auto|scroll/.test(cs.overflowX) || (cs.scrollSnapType && cs.scrollSnapType !== 'none')
        const totalW = rects.reduce((a, r) => a + r.width, 0)
        const named = NAMED.test(String(el.className || '') + ' ' + String(el.id || '')) || NAMED.test(String(el.parentElement?.className || ''))
        const made = /\bvaic\b/.test(String(el.className || ''))
        let shape: Widget['shape'] | null = null
        let evidence = ''
        if (made) { shape = 'montado'; evidence = 'já foi montado com make_carousel' }
        else if (slides.length >= 3 && (stackedPairs >= Math.min(slides.length, 3) || (hidden >= slides.length - 1 && sameClass))) { shape = 'empilhado'; evidence = `${slides.length} blocos iguais na mesma posição, só ${Math.max(0, slides.length - hidden)} visível` }
        else if (slides.length >= 3 && scrollsX && totalW > el.getBoundingClientRect().width * 1.2) { shape = 'trilho'; evidence = 'faixa horizontal com rolagem' }
        else if (slides.length >= 3 && findOriginalDots(comp, slides.length)) { shape = 'com_bolinhas'; evidence = `${slides.length} slides com uma fileira de ${slides.length} bolinhas ao lado` }
        else if (named) { shape = 'nomeado'; evidence = `classe "${clip(String(el.className || el.parentElement?.className || ''), 40)}"` }
        if (shape) {
          const visible = els.filter(e => visibleNow(e, win)).length
          const animated = cssOf.some(c => c.animationName && c.animationName !== 'none')
          const state = shape === 'montado' ? (animated ? 'animado' : 'montado, confira com check_motion')
            : animated ? 'já tem animação'
              : shape === 'trilho' ? 'rolável com o dedo/mouse; sem setas nem autoplay'
                : visible <= 1 ? `parado: só ${visible} de ${slides.length} aparece e nada troca (o script do original foi removido)`
                  : `${visible} de ${slides.length} aparecem juntos${stackedPairs ? ' sobrepostos' : ' um embaixo do outro'}; nada troca`
          const title = clip(txt(els[0]), 40)
          found.push({ id: stableId(comp), kind: 'carousel', shape, slides: slides.length, slideIds: slides.map(stableId), where: title ? `começa com "${title}"` : `${el.tagName.toLowerCase()}`, evidence, state })
          return
        }
      }
    }
    for (const k of kids) scan(k, depth + 1)
  }
  scan(contentRoot(ctx), 0)
  return found
}

export function widgetsText(list: Widget[]): string {
  if (!list.length) return 'Nenhum carrossel ou slider detectado.'
  return list.map(w => `- carrossel id ${w.id}: ${w.slides} slides, ${w.where}. Estado: ${w.state}. (${w.evidence})`).join('\n')
}

/* ═════════════════════════ a carousel that works without a script ═════════════════════════ */

const safe = (s: string) => s.replace(/[^a-z0-9]/gi, '').slice(-8) || 'x'

function removeRules(ctx: EngineCtx, key: string) {
  const css = ctx.editor.Css as any
  const drop = css.getAll().models.filter((r: any) => { try { const t = String(r.toCSS?.({}) || ''); return t.includes(`vaic-${key}`) || t.includes(`vaic-w-${key}`) || t.includes(`vaic-gone-${key}`) || t.includes(`vaic-row-${key}`) } catch { return false } })
  drop.forEach((r: any) => css.remove(r))
}

export interface CarouselOptions { interval: number; dots: boolean; pauseOnHover: boolean; accent?: string; muted?: string }

const STATE_CLASS = /\b(on|active|is-active|current|selected|is-current)\b/g
const ARROW = /(prev|next|anterior|pr[oó]xim|seta|arrow|chevron|‹|›|«|»|←|→)/i

/**
 * The original pager of the carousel: a sibling holding exactly one tiny, textless element per slide (its dots). It lost its script
 * with everything else, so it sits there doing nothing. Returns it so it can be wired to the new carousel instead of showing a dead
 * row of dots next to a new row.
 */
function findOriginalDots(comp: Comp, n: number): { wrap: Comp; items: Comp[] } | null {
  const parent = comp.parent?.()
  if (!parent) return null
  for (const sib of realChildren(parent)) {
    if (sib === comp) continue
    const items = realChildren(sib).filter(i => !/^(input)$/i.test(String(i.getEl()?.tagName)))
    if (items.length !== n) continue
    const els = items.map(i => i.getEl() as HTMLElement)
    if (new Set(els.map(e => e.tagName)).size !== 1) continue
    if (els.every(e => { const r = e.getBoundingClientRect(); return r.width <= 40 && r.height <= 40 && txt(e).length <= 2 })) return { wrap: sib, items }
  }
  return null
}

/** Previous / next buttons next to the carousel: they cannot work without a script, so they are hidden instead of left dead. */
function findDeadArrows(comp: Comp, skip: Comp | null): Comp[] {
  const parent = comp.parent?.()
  if (!parent) return []
  const out: Comp[] = []
  const look = (c: Comp, depth: number) => {
    if (depth > 2 || out.length >= 4) return
    for (const k of realChildren(c)) {
      if (k === comp || k === skip) continue
      const e = k.getEl() as HTMLElement
      const label = `${e.getAttribute('aria-label') || ''} ${e.getAttribute('title') || ''} ${String(e.className || '')} ${txt(e).slice(0, 3)}`
      const r = e.getBoundingClientRect()
      if (/^(button|a)$/i.test(e.tagName) && r.width <= 72 && r.height <= 72 && ARROW.test(label) && !/\bvaic-/.test(String(e.className || ''))) out.push(k)
      else look(k, depth + 1)
    }
  }
  look(parent, 0)
  return out.length >= 1 && out.length <= 4 ? out : []
}

export function makeCarousel(ctx: EngineCtx, comp: Comp, o: CarouselOptions): { key: string; slides: number; interval: number; dots: boolean; slideIds: string[]; dotsMode: 'originais' | 'novas' | 'nenhuma'; hiddenControls: number } {
  const ed: any = ctx.editor
  const win = winOf(ctx)
  const el = comp.getEl?.()
  if (!win || !isElement(el)) throw new Error('O contêiner não aparece na tela.')
  const key = safe(stableId(comp))
  const parent = comp.parent?.()

  // start clean when this container was already made into a carousel (calling the tool again changes it, never doubles it)
  removeRules(ctx, key)
  for (const k of realChildren(comp)) if (isControl(k)) k.remove()
  if (parent) { for (const k of realChildren(parent)) if (isControl(k)) k.remove(); parent.removeClass?.(`vaic-w-${key}`) }

  const kids = realChildren(comp)
  const tagOf = (k: Comp) => String(k.getEl().tagName)
  const tag = mode(kids.map(tagOf))
  const slides = kids.filter(k => tagOf(k) === tag)
  if (slides.length < 2) throw new Error(`Este contêiner tem ${slides.length} filho(s) do mesmo tipo: um carrossel precisa de pelo menos 2 slides. Use find_widgets para ver onde estão os slides.`)

  const N = slides.length
  const T = Math.min(15, Math.max(2, o.interval || 5))
  const D = N * T
  const w = 100 / N
  const fade = Math.min(1.5, w / 4)
  const accent = o.accent || '#ffffff'
  const muted = o.muted || 'rgba(255,255,255,.35)'

  // display of the slides: a slide the original hid with display:none needs a real display to take part
  const shown = slides.map(s => win.getComputedStyle(s.getEl()).display).find(d => d !== 'none') || 'block'
  const needDisplay = slides.map((s, i) => (win.getComputedStyle(s.getEl()).display === 'none' ? i : -1)).filter(i => i >= 0)

  const orig = o.dots ? findOriginalDots(comp, N) : null
  const arrows = findDeadArrows(comp, orig?.wrap ?? null)
  // what the original dots looked like (so the new ones keep the site's own style): the "on" dot and a normal one
  let dotOn: { bg: string; width: string; height: string } | null = null
  let dotOff: { bg: string; width: string; height: string } | null = null
  if (orig) {
    const els = orig.items.map(i => i.getEl() as HTMLElement)
    const on = els.find(e => { STATE_CLASS.lastIndex = 0; return STATE_CLASS.test(String(e.className || '')) })
    const off = els.find(e => e !== on) || els[0]
    const snap = (e: HTMLElement) => { const c = win.getComputedStyle(e); return { bg: c.backgroundColor, width: c.width, height: c.height } }
    dotOff = snap(off)
    dotOn = on ? snap(on) : null
  }

  // a pager that lays its dots out as a COLUMN (a rebuilt section lost the flex row of the original) goes back to a row
  let dotsAsColumn = false
  if (orig) {
    const els = orig.items.map(i => i.getEl() as HTMLElement)
    const rs = els.map(e => e.getBoundingClientRect())
    dotsAsColumn = rs.length >= 3 && rs.every(r => Math.abs(r.left - rs[0].left) <= 2) && rs.slice(1).every((r, k) => r.top - rs[k].top >= 4)
    if (dotsAsColumn) orig.wrap.addClass(`vaic-row-${key}`)
  }
  comp.addClass(['vaic', `vaic-${key}`])
  slides.forEach((s, i) => { s.addClass(['vaic-s', `vaic-s-${i}`]) })
  // the selector that reaches both the slides and the dots: the container itself, or, with the site's own dots, the element holding both
  const A = orig && parent ? `.vaic-w-${key}` : `.vaic-${key}`
  if (orig && parent) parent.addClass(`vaic-w-${key}`)

  let css = ''
  css += `.vaic-${key}{display:grid!important;position:relative!important;height:auto!important;min-height:0!important;}`
  css += `.vaic-${key}>.vaic-s{grid-area:1/1!important;position:relative!important;inset:auto!important;transform:none!important;margin:0!important;width:100%!important;min-width:0!important;box-sizing:border-box;opacity:0;visibility:hidden;animation:vaic-${key}-s ${D}s linear infinite!important;}`
  css += `@keyframes vaic-${key}-s{0%{opacity:0;visibility:hidden}${fade}%{opacity:1;visibility:visible}${(w - fade).toFixed(3)}%{opacity:1;visibility:visible}${w.toFixed(3)}%{opacity:0;visibility:hidden}100%{opacity:0;visibility:hidden}}`
  slides.forEach((_, i) => { css += `.vaic-${key}>.vaic-s-${i}{animation-delay:${(i * T).toFixed(2)}s!important;${needDisplay.includes(i) ? `display:${shown}!important;` : ''}}` })
  if (o.pauseOnHover) css += `${A}:hover .vaic-s,${A}:hover .vaic-dot{animation-play-state:paused;}`

  let dotsMode: 'originais' | 'novas' | 'nenhuma' = 'nenhuma'
  if (o.dots) {
    const inputs = slides.map((_, i) => `<input type="radio" name="vaic-${key}" id="vaic-${key}-${i}" class="vaic-in" aria-label="Slide ${i + 1}">`).join('')
    const actBg = dotOn?.bg || accent
    const idleBg = dotOff?.bg || muted
    if (orig && parent) {
      dotsMode = 'originais'
      parent.components().add(inputs, { at: 0 })
      // each original dot becomes a <label> for the matching radio, keeping its classes (minus the "on" state) and its look
      const fresh: Comp[] = []
      orig.items.forEach((item, i) => {
        const attrs = { ...(item.getAttributes?.() || {}) } as Record<string, string>
        const cls = String(attrs.class || item.getClasses?.().join(' ') || '').replace(STATE_CLASS, '').replace(/\s+/g, ' ').trim()
        delete attrs.class; delete attrs.type; delete attrs.onclick; delete attrs.id
        const rest = Object.entries(attrs).map(([k, v]) => `${k}="${String(v).replace(/"/g, '&quot;')}"`).join(' ')
        const r = item.replaceWith(`<label for="vaic-${key}-${i}" class="${cls} vaic-dot vaic-d-${i}" ${rest}></label>`)
        fresh.push(Array.isArray(r) ? r[0] : r)
      })
      const widthMoves = dotOn && dotOff && dotOn.width !== dotOff.width
      const frame = (bg: string, on: boolean) => `background-color:${bg};${widthMoves ? `width:${on ? dotOn!.width : dotOff!.width};` : `transform:scale(${on ? 1.25 : 1});`}`
      css += `${A}>.vaic-in{position:absolute!important;opacity:0;width:1px;height:1px;margin:0;pointer-events:none;}`
      css += `${A} .vaic-dot{pointer-events:auto;cursor:pointer;background-color:${idleBg};animation:vaic-${key}-d ${D}s linear infinite!important;}`
      css += `@keyframes vaic-${key}-d{0%{${frame(actBg, true)}}${(w - fade).toFixed(3)}%{${frame(actBg, true)}}${w.toFixed(3)}%{${frame(idleBg, false)}}100%{${frame(idleBg, false)}}}`
      slides.forEach((_, i) => {
        css += `${A} .vaic-d-${i}{animation-delay:${(i * T).toFixed(2)}s!important;}`
        css += `${A}:has(#vaic-${key}-${i}:checked) .vaic-s-${i}{opacity:1!important;visibility:visible!important;}`
        css += `${A}:has(#vaic-${key}-${i}:checked) .vaic-d-${i}{${frame(actBg, true)}}`
      })
      css += `${A}:has(.vaic-in:checked) .vaic-s{animation:none!important;}`
      css += `${A}:has(.vaic-in:checked) .vaic-dot{animation:none!important;${frame(idleBg, false)}}`
      void fresh
    } else {
      dotsMode = 'novas'
      const labels = slides.map((_, i) => `<label for="vaic-${key}-${i}" class="vaic-dot vaic-d-${i}" title="Slide ${i + 1}"></label>`).join('')
      comp.components().add(inputs + `<div class="vaic-nav">${labels}</div>`, { at: comp.components().length })
      css += `.vaic-${key}>.vaic-in{position:absolute!important;opacity:0;width:1px;height:1px;margin:0;pointer-events:none;}`
      css += `.vaic-${key}>.vaic-nav{position:absolute!important;left:0;right:0;bottom:10px;display:flex;justify-content:center;gap:8px;z-index:3;pointer-events:none;}`
      css += `.vaic-${key} .vaic-dot{pointer-events:auto;cursor:pointer;display:block;width:10px;height:10px;border-radius:999px;background:${muted};animation:vaic-${key}-d ${D}s linear infinite!important;}`
      css += `@keyframes vaic-${key}-d{0%{background:${accent};transform:scale(1.25)}${(w - fade).toFixed(3)}%{background:${accent};transform:scale(1.25)}${w.toFixed(3)}%{background:${muted};transform:scale(1)}100%{background:${muted};transform:scale(1)}}`
      slides.forEach((_, i) => {
        css += `.vaic-${key} .vaic-d-${i}{animation-delay:${(i * T).toFixed(2)}s!important;}`
        css += `.vaic-${key}:has(#vaic-${key}-${i}:checked) .vaic-s-${i}{opacity:1!important;visibility:visible!important;}`
        css += `.vaic-${key}:has(#vaic-${key}-${i}:checked) .vaic-d-${i}{background:${accent}!important;transform:scale(1.25)!important;}`
      })
      css += `.vaic-${key}:has(.vaic-in:checked) .vaic-s{animation:none!important;}`
      css += `.vaic-${key}:has(.vaic-in:checked) .vaic-dot{animation:none!important;background:${muted};transform:none;}`
    }
  }
  // controls that only a script could drive (previous/next) are hidden: a dead arrow is worse than none
  if (dotsAsColumn) css += `.vaic-row-${key}{display:flex!important;flex-direction:row!important;flex-wrap:wrap;align-items:center;gap:7px;}`
  arrows.forEach(a => a.addClass(`vaic-gone-${key}`))
  if (arrows.length) css += `.vaic-gone-${key}{display:none!important;}`
  css += `@media (prefers-reduced-motion:reduce){.vaic-${key}>.vaic-s,${A} .vaic-dot{animation:none!important;}.vaic-${key}>.vaic-s-0{opacity:1!important;visibility:visible!important;}}`
  ed.Css.addRules(css)
  return { key, slides: N, interval: T, dots: o.dots, slideIds: slides.map(stableId), dotsMode, hiddenControls: arrows.length }
}

/**
 * Looks at a carousel over time, the way a visitor would: which slides can be seen, sample after sample. "Done" for a carousel means
 * this said it turns, never that the CSS was written.
 */
export async function checkMotion(ctx: EngineCtx, comp: Comp, seconds: number): Promise<{ verdict: 'gira' | 'parado' | 'empilhado' | 'sem_slide_visivel' | 'inconclusivo'; slides: number; samples: string[]; message: string }> {
  const win = winOf(ctx)
  const el = comp.getEl?.()
  if (!win || !isElement(el)) return { verdict: 'inconclusivo', slides: 0, samples: [], message: 'O elemento não aparece na tela.' }
  const marked = realChildren(comp).filter(k => /\bvaic-s\b/.test(String(k.getEl().className || '')))
  const kids = marked.length ? marked : (() => { const all = realChildren(comp).filter(k => !isControl(k)); const t = mode(all.map(k => String(k.getEl().tagName))); return all.filter(k => String(k.getEl().tagName) === t) })()
  const els = kids.map(k => k.getEl() as HTMLElement)
  const N = els.length
  const sec = Math.min(10, Math.max(2, seconds))
  const steps = Math.max(6, Math.round(sec * 2))
  const samples: string[] = []
  let together = 0
  for (let s = 0; s < steps; s++) {
    const vis = els.map((e, i) => (visibleNow(e, win) ? i : -1)).filter(i => i >= 0)
    samples.push(vis.join('+') || '-')
    if (vis.length >= 2) together++
    if (s < steps - 1) await new Promise(r => setTimeout(r, (sec * 1000) / steps))
  }
  const single = samples.filter(x => /^\d+$/.test(x))
  const distinct = new Set(single)
  let verdict: 'gira' | 'parado' | 'empilhado' | 'sem_slide_visivel' | 'inconclusivo'
  let message: string
  if (distinct.size >= 2) { verdict = 'gira'; message = `Funciona: ${distinct.size} slides diferentes apareceram em ${sec}s (um de cada vez).` }
  else if (together >= Math.ceil(steps / 2)) { verdict = 'empilhado'; message = `Quebrado: vários slides aparecem ao mesmo tempo (${N} no total), um sobre o outro ou um embaixo do outro. Use make_carousel no contêiner dos slides.` }
  else if (!single.length) { verdict = 'sem_slide_visivel'; message = 'Quebrado: nenhum slide ficou visível durante a observação.' }
  else { verdict = 'parado'; message = `Não troca: só o slide ${[...distinct][0]} apareceu em ${sec}s. Se o intervalo é maior que isso, aumente "seconds" no check_motion; senão, use make_carousel.` }
  return { verdict, slides: N, samples: samples.slice(0, 24), message }
}
